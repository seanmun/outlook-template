/**
 * Generates fictional sample hero images (simple gradients) as base64 PNGs.
 * Run: pnpm tsx scripts/generate-samples.ts
 */
import { deflateSync } from "node:zlib";
import { writeFileSync } from "node:fs";

const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = (buf: Buffer) => {
  let c = 0xffffffff;
  for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
const chunk = (type: string, data: Buffer) => {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
};
const hex = (h: string) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));

function gradientPng(w: number, h: number, from: string, to: string): Buffer {
  const [r1, g1, b1] = hex(from), [r2, g2, b2] = hex(to);
  const raw = Buffer.alloc((w * 3 + 1) * h);
  for (let y = 0; y < h; y++) {
    raw[y * (w * 3 + 1)] = 0;
    for (let x = 0; x < w; x++) {
      const t = (x / (w - 1)) * 0.7 + (y / (h - 1)) * 0.3;
      const o = y * (w * 3 + 1) + 1 + x * 3;
      raw[o] = Math.round(r1 + (r2 - r1) * t);
      raw[o + 1] = Math.round(g1 + (g2 - g1) * t);
      raw[o + 2] = Math.round(b1 + (b2 - b1) * t);
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8; ihdr[9] = 2; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", ihdr), chunk("IDAT", deflateSync(raw, { level: 9 })), chunk("IEND", Buffer.alloc(0)),
  ]);
}

const samples = [
  { id: "hero-harbor", label: "Sample gradient (navy to pine)", from: "#14304a", to: "#1f6f50" },
  { id: "hero-lumen", label: "Sample gradient (violet to lilac)", from: "#5b3fd6", to: "#c9bdf5" },
  { id: "hero-copper", label: "Sample gradient (espresso to copper)", from: "#2b2420", to: "#b0602c" },
];
const W = 1200, H = 520;
const out = samples.map((s) => ({ ...s, width: W, height: H, mimeType: "image/png", base64: gradientPng(W, H, s.from, s.to).toString("base64") }));
writeFileSync(
  "src/lib/email/samples.generated.ts",
  `// Generated by scripts/generate-samples.ts. Fictional placeholder imagery only.\n` +
  `export const SAMPLE_IMAGES = ${JSON.stringify(out.map(({ id, label, width, height, mimeType, base64 }) => ({ id, label, width, height, mimeType, base64 })), null, 2)} as const;\n`,
);
