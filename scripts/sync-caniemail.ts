/**
 * Pulls Can I email's data (https://www.caniemail.com/api/data.json, MIT licence,
 * © Rémi Parmentier) and keeps features that are unsupported ("n") in EVERY
 * tested version of classic Outlook for Windows. Writes a static file so the site
 * never depends on caniemail.com at runtime.
 *
 *   pnpm sync:caniemail
 */
import { writeFileSync } from "node:fs";

type Feature = { slug: string; title: string; url: string; category: string; stats: Record<string, Record<string, Record<string, string>>> };
type Api = { api_version: string; last_update_date: string; data: Feature[] };

// Popular ones lead the rotation; everything else follows in random order on the client.
const GREATEST_HITS = ["border-radius", "display:flex", "display:grid", "background-image", "box-shadow", "@media (prefers-color-scheme)", "max-width", "linear-gradient()", "position", ":hover", "animation", "object-fit", "rgba()", "opacity", "margin"];

async function main() {
  const res = await fetch("https://www.caniemail.com/api/data.json");
  if (!res.ok) throw new Error(`caniemail API returned ${res.status}`);
  const api = (await res.json()) as Api;
  const nos = api.data
    .filter((f) => {
      const win = f.stats.outlook?.windows;
      if (!win) return false;
      const values = Object.values(win);
      return values.length > 0 && values.every((v) => v.trim().split(/\s+/)[0] === "n");
    })
    .map((f) => ({ title: f.title.trim(), url: f.url }));
  nos.sort((a, b) => {
    const ia = GREATEST_HITS.indexOf(a.title), ib = GREATEST_HITS.indexOf(b.title);
    return (ia < 0 ? 999 : ia) - (ib < 0 ? 999 : ib) || a.title.localeCompare(b.title);
  });
  const hits = nos.filter((n) => GREATEST_HITS.includes(n.title)).length;
  writeFileSync(
    "src/lib/marketing/outlook-nos.generated.ts",
    `// Generated by scripts/sync-caniemail.ts from https://www.caniemail.com/api/data.json
// Data: Can I email, MIT License, (c) Rémi Parmentier. https://github.com/hteumeuleu/caniemail
// Source last updated: ${api.last_update_date} (API ${api.api_version}).
// Features unsupported in every tested version of classic Outlook for Windows.

export const CANIEMAIL_LAST_UPDATE = ${JSON.stringify(api.last_update_date.slice(0, 10))};
export const OUTLOOK_WINDOWS_GREATEST_HITS = ${hits};
export const OUTLOOK_WINDOWS_NOS: { title: string; url: string }[] = ${JSON.stringify(nos, null, 2)};
`,
  );
  console.log(`${nos.length} unsupported features (${hits} greatest hits first), source updated ${api.last_update_date}`);
}
main();
